import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('.', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/services/mail/mailCryptoEntry.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  write: false,
  nodePaths: [root + 'node_modules'],
  plugins: [
    {
      name: 'noble-extension-aliases',
      setup(builder) {
        builder.onResolve(
          {filter: /^@noble\/(hashes|ciphers|post-quantum)\/[^.]+$/},
          args => ({path: root + 'node_modules/' + args.path + '.js'}),
        );
      },
    },
  ],
});
const output =
  '// Generated by npm run build:mail-crypto. Do not edit.\nexport default ' +
  JSON.stringify(result.outputFiles[0].text) +
  ';\n';
const path = new URL('src/services/mail/mailCryptoBundle.js', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')) !== output)
    throw new Error('Run npm run build:mail-crypto');
} else await writeFile(path, output);
